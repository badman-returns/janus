#!/usr/bin/env bash
# Builds Janus.app — the one thing to double-click. It brings the fleet machine up (which starts
# the voice loop and the menu-bar shell), waits for the loop, and opens the front door in Chrome.
#
#   bash voice/app/make-app.sh                  # -> ~/Applications/Janus.app
#   JANUS_APP_DIR=/tmp/x bash .../make-app.sh   # -> /tmp/x/Janus.app  (the test)
#
# The launcher carries this checkout's absolute path, written in below, so a bundle built from one
# worktree keeps pointing at that worktree. Rebuild it after moving the checkout. Built locally and
# never downloaded, so Gatekeeper has nothing to quarantine and there is nothing to sign.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BRAIN="$HOME/brain"
DEST="${JANUS_APP_DIR:-$HOME/Applications}"
APP="$DEST/Janus.app"

mkdir -p "$DEST"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Janus</string>
  <key>CFBundleDisplayName</key><string>Janus</string>
  <key>CFBundleIdentifier</key><string>dev.janus.frontdoor</string>
  <key>CFBundleExecutable</key><string>janus</string>
  <key>CFBundleIconFile</key><string>Janus</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
</dict></plist>
PLIST

# ---- the launcher. REPO and BRAIN are baked in; everything after them is verbatim.
{
  echo '#!/bin/bash'
  echo '# Janus, the front door. Generated by voice/app/make-app.sh — edit that, not this.'
  echo "REPO=$(printf %q "$REPO")"
  echo "BRAIN=$(printf %q "$BRAIN")"
  cat <<'LAUNCH'
set -u
# A double-clicked app inherits a bare PATH, and tmux, node and claude all live outside it. Without
# this the machine cannot start and the failure is invisible.
export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
LOG="$HOME/Library/Logs/Janus.log"; mkdir -p "$(dirname "$LOG")"; exec >>"$LOG" 2>&1
echo "--- $(date '+%F %T') Janus.app"

# Already running? Then this is just "open the window".
tmux has-session -t dm-fleet 2>/dev/null || (cd "$BRAIN" && bash "$REPO/plugin/scripts/orchestrator.sh" --no-open)

# The window is worth nothing until the loop answers, so wait for it — up to 20 s.
for i in $(seq 1 20); do
  curl -s -m 1 http://127.0.0.1:8790/state >/dev/null 2>&1 && break
  sleep 1
done

# The same URL the shell's "Show Janus" opens, from the same code, so the two can never diverge.
FRONT=$(cd "$BRAIN" && PYTHONPATH="$REPO/voice" "$REPO/voice/.venv/bin/python" -c 'import shell; print(shell.FRONT)')
[ -n "$FRONT" ] || { echo "janus: no mission control port — did the machine come up?"; exit 1; }
echo "janus: opening $FRONT"
CHROME="/Applications/Google Chrome.app"
if [ -d "$CHROME" ]; then open -na "$CHROME" --args "--app=$FRONT" --window-size=1280,820
else open "$FRONT"; fi
LAUNCH
} > "$APP/Contents/MacOS/janus"
chmod +x "$APP/Contents/MacOS/janus"

# ---- the icon: the menu-bar ring in the accent colour, drawn at every size iconutil wants
SET=$(mktemp -d)/Janus.iconset; mkdir -p "$SET"
for s in 16 32 128 256 512; do
  python3 "$REPO/voice/app/icon.py" "$SET/icon_${s}x${s}.png" "$s" > /dev/null
  python3 "$REPO/voice/app/icon.py" "$SET/icon_${s}x${s}@2x.png" "$((s * 2))" > /dev/null
done
iconutil -c icns "$SET" -o "$APP/Contents/Resources/Janus.icns"
rm -rf "$(dirname "$SET")"

touch "$APP"   # nudge Finder to notice the new icon
echo "built $APP"
